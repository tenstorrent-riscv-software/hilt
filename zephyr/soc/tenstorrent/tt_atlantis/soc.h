#ifndef SOC_TT_ATLANTIS_SOC_H_
#define SOC_TT_ATLANTIS_SOC_H_

/* SMN_SS: memories local to the RCPU */
#define ATLANTIS_RCPU_ITCM_BASE		0x00000000UL	/* 256 KiB */
#define ATLANTIS_RCPU_ITCM_SIZE		0x00040000UL
#define ATLANTIS_RCPU_ROM_BASE		0x00040000UL	/* 256 KiB mask ROM (ZSBL) */
#define ATLANTIS_RCPU_ROM_SIZE		0x00040000UL
#define ATLANTIS_RCPU_DTCM_BASE		0x20000000UL	/* 256 KiB */
#define ATLANTIS_RCPU_DTCM_SIZE		0x00040000UL
#define ATLANTIS_SMN_SRAM_BASE		0x20100000UL	/* 1 MiB SMN scratchpad */
#define ATLANTIS_SMN_SRAM_SIZE		0x00100000UL

/* SOC_SS */
#define ATLANTIS_PRCM_BASE		0x40000000UL
#define ATLANTIS_PVT_BASE		0x40010000UL
#define ATLANTIS_TIMER_BASE		0x40020000UL
#define ATLANTIS_WDT0_BASE		0x40030000UL
#define ATLANTIS_WDT1_BASE		0x40040000UL
#define ATLANTIS_PMU_BASE		0x40050000UL
#define ATLANTIS_IO_CTRL_BASE		0x40060000UL
#define ATLANTIS_INTR_CTRL_BASE		0x40070000UL
#define ATLANTIS_MAILBOX_BASE		0x40100000UL
#define ATLANTIS_SMN_FIREWALL_BASE	0x41010000UL
#define ATLANTIS_NOCM_FIREWALL_BASE	0x41020000UL

/* LSIO peripherals, one 64 KiB window each */
#define ATLANTIS_SPI_BASE(n)		(0x48000000UL + (n) * 0x10000UL)	/* n = 0..3 */
#define ATLANTIS_I2C_BASE(n)		(0x48040000UL + (n) * 0x10000UL)	/* n = 0..4 */
#define ATLANTIS_UART_BASE(n)		(0x48100000UL + (n) * 0x10000UL)	/* n = 0..4 */
#define ATLANTIS_GPIO_BASE		0x48150000UL
#define ATLANTIS_I2S_BASE(n)		(0x48170000UL + (n) * 0x10000UL)	/* n = 0..1 */
#define ATLANTIS_SMNDMA_BASE(n)		(0x48200000UL + (n) * 0x10000UL)	/* n = 0..1 */
#define ATLANTIS_CAN_BASE(n)		(0x48300000UL + (n) * 0x10000UL)	/* n = 0..1 */
#define ATLANTIS_QSPI_BASE		0x4A000000UL	/* 32 MiB */

/* SEC_SS */
#define ATLANTIS_OTP_BASE		0x50000000UL
#define ATLANTIS_TRNG_BASE		0x50600000UL
#define ATLANTIS_SPACC_BASE		0x50800000UL

/* DRAM window. The RCPU sees DRAM through a 1 GiB window
 */
#define ATLANTIS_DRAM_BASE		0x60000000UL
#define ATLANTIS_DRAM_SIZE		0x40000000UL

/* Ascalon cluster and CPL */
#define ATLANTIS_ASC_MMR_BASE		0xA2000000UL
#define ATLANTIS_CPL_MMR_BASE		0xA2100000UL
#define ATLANTIS_CPL_SRAM_BASE		0xA2140000UL

/* RCPU core-local blocks */
#define ATLANTIS_RCPU_CLIC_BASE		0xE000E000UL
#define ATLANTIS_RCPU_CLIC_SIZE		0x2000UL
#define ATLANTIS_RCPU_CLINT_BASE	0xE0020000UL
#define ATLANTIS_RCPU_CLINT_MSIP	(ATLANTIS_RCPU_CLINT_BASE + 0x0000UL)
#define ATLANTIS_RCPU_CLINT_MTIMECMP	(ATLANTIS_RCPU_CLINT_BASE + 0x4000UL)
#define ATLANTIS_RCPU_CLINT_MTIME	(ATLANTIS_RCPU_CLINT_BASE + 0xBFF8UL)

/* PRCM registers used by the SoC glue */
#define ATLANTIS_PRCM_GLOBAL_SOFT_RST	0x024
#define ATLANTIS_PRCM_RCPU_BOOT_MODE	0x1B0
#define ATLANTIS_PRCM_RCPU_SOFT_RST	0x244

/* Writing this key to GLOBAL_SOFT_RST resets the whole SoC except the PMU
 * and CPU debug logic; the RCPU reboots through the mask ROM.
 */
#define ATLANTIS_GLOBAL_SOFT_RST_KEY	0xAA55A5A5UL

#define ATLANTIS_RCPU_IRQ_MSIP		3
#define ATLANTIS_RCPU_IRQ_MTIP		7
#define ATLANTIS_RCPU_IRQ_MEIP		11
#define ATLANTIS_RCPU_EXT_IRQ(n)	(16 + (n))

#define ATLANTIS_RCPU_IRQ_WDT0		ATLANTIS_RCPU_EXT_IRQ(3)
#define ATLANTIS_RCPU_IRQ_WDT1		ATLANTIS_RCPU_EXT_IRQ(4)
#define ATLANTIS_RCPU_IRQ_MAILBOX(n)	ATLANTIS_RCPU_EXT_IRQ(14 + (n))	/* n = 0..3 */
#define ATLANTIS_RCPU_IRQ_ASC_RAS	ATLANTIS_RCPU_EXT_IRQ(18)
#define ATLANTIS_RCPU_IRQ_ASC_TJ_SHUTDOWN ATLANTIS_RCPU_EXT_IRQ(19)
#define ATLANTIS_RCPU_IRQ_ASC_CONFIG_DONE ATLANTIS_RCPU_EXT_IRQ(20)
#define ATLANTIS_RCPU_IRQ_ASC_DFS	ATLANTIS_RCPU_EXT_IRQ(21)
#define ATLANTIS_RCPU_IRQ_ASC_ZKR	ATLANTIS_RCPU_EXT_IRQ(22)
#define ATLANTIS_RCPU_IRQ_ASC_NDM_RESET	ATLANTIS_RCPU_EXT_IRQ(23)
#define ATLANTIS_RCPU_IRQ_ASC_TIMEOUT	ATLANTIS_RCPU_EXT_IRQ(26)
#define ATLANTIS_RCPU_IRQ_OTP		ATLANTIS_RCPU_EXT_IRQ(28)
#define ATLANTIS_RCPU_IRQ_TRNG		ATLANTIS_RCPU_EXT_IRQ(29)
#define ATLANTIS_RCPU_IRQ_SPACC		ATLANTIS_RCPU_EXT_IRQ(30)
#define ATLANTIS_RCPU_IRQ_QSPI		ATLANTIS_RCPU_EXT_IRQ(32)
#define ATLANTIS_RCPU_IRQ_I2C(n)	ATLANTIS_RCPU_EXT_IRQ(33 + (n))	/* n = 0..4 */
#define ATLANTIS_RCPU_IRQ_UART(n)	ATLANTIS_RCPU_EXT_IRQ(38 + (n))	/* n = 0..4 */
#define ATLANTIS_RCPU_IRQ_SPI(n)	ATLANTIS_RCPU_EXT_IRQ(43 + (n))	/* n = 0..3 */
#define ATLANTIS_RCPU_IRQ_GPIO		ATLANTIS_RCPU_EXT_IRQ(47)
#define ATLANTIS_RCPU_IRQ_SDHCI(n)	ATLANTIS_RCPU_EXT_IRQ(48 + (n))	/* n = 0..1 */

#endif /* SOC_TT_ATLANTIS_SOC_H_ */
